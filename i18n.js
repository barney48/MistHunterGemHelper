const LANG_STORAGE_KEY = "mistHunterGemHelper.lang";

let LANG = (function () {
  try {
    const saved = localStorage.getItem(LANG_STORAGE_KEY);
    return I18N[saved] ? saved : "en";
  } catch (e) {
    return "en";
  }
})();

function setLang(lang) {
  if (!I18N[lang]) return;
  LANG = lang;
  try { localStorage.setItem(LANG_STORAGE_KEY, lang); } catch (e) {}
}

function t(key, params) {
  let s = I18N[LANG][key];
  if (s == null) s = I18N.en[key];
  if (s == null) s = key;
  if (params) {
    for (const k in params) s = s.split("{" + k + "}").join(params[k]);
  }
  return s;
}

// Display-only translations for stored English identifiers; fall back to the
// raw value (covers custom group names the user typed, and the EN locale).
function displayGroup(group) {
  return I18N[LANG]["group." + group] || group;
}

function displayGemType(type) {
  return I18N[LANG]["gemtype." + type] || type;
}
